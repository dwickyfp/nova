"""Append-only governed events in the caller's metadata transaction."""

from __future__ import annotations

from dataclasses import dataclass, field, fields
from datetime import UTC, datetime
from typing import Any
from uuid import UUID

import psycopg
from psycopg.pq import TransactionStatus
from psycopg.types.json import Jsonb

from app.common.audit_text import fit_audit_text
from app.common.sql_guard import redact_sql_credentials
from app.core.metadata_db import MetadataConflict


def _text(value: Any, limit: int) -> None:
    if not isinstance(value, str) or len(value) > limit or "\x00" in value:
        raise ValueError("Invalid audit field")
    try:
        value.encode("utf-8")
    except UnicodeError:
        raise ValueError("Invalid audit field") from None


@dataclass(frozen=True, slots=True)
class AuditIdentity:
    record_id: UUID
    event_time: datetime

    def __post_init__(self) -> None:
        if (
            not isinstance(self.record_id, UUID)
            or self.record_id.int == 0
            or not isinstance(self.event_time, datetime)
            or self.event_time.tzinfo is None
            or self.event_time.utcoffset() is None
        ):
            raise ValueError("Invalid audit identity")
        try:
            object.__setattr__(self, "event_time", self.event_time.astimezone(UTC))
        except (OverflowError, ValueError):
            raise ValueError("Invalid audit identity") from None


@dataclass(frozen=True, slots=True, repr=False)
class AuditEvent:
    event_type: str
    action: str
    object_type: str
    object_name: str
    status: str
    query_id: str | None = None
    sql_text: str | None = None
    rewritten_sql: str | None = None
    error_message: str | None = None
    duration_ms: int | None = None
    rows_affected: int | None = None
    session_id: str | None = None
    file_id: str | None = None
    database_name: str | None = None
    schema_name: str | None = None
    decision: str | None = None
    ranger_policy_ids: str | None = None
    nova_execution_id: str | None = None
    engine_query_ids: tuple[str, ...] | None = field(default=None)
    execution_purpose: str | None = None
    ip_address: str | None = None
    client_ip: str | None = None

    def __post_init__(self) -> None:
        limits = {
            "event_type": 64,
            "action": 128,
            "object_type": 64,
            "object_name": 512,
            "status": 32,
            "query_id": 36,
            "session_id": 64,
            "file_id": 64,
            "database_name": 128,
            "schema_name": 128,
            "decision": 32,
            "ranger_policy_ids": 2048,
            "nova_execution_id": 64,
            "execution_purpose": 16,
            "ip_address": 45,
            "client_ip": 45,
        }
        for name in ("event_type", "action", "object_type", "object_name", "status"):
            if not getattr(self, name):
                raise ValueError("Missing audit field")
        if self.event_type == "metadata":
            raise ValueError("Metadata success audit is generated by its transaction")
        for name, limit in limits.items():
            value = getattr(self, name)
            if value is not None:
                _text(value, limit)
        for name in ("sql_text", "rewritten_sql", "error_message"):
            value = getattr(self, name)
            if value is not None:
                _text(value, 4_000_000)
                object.__setattr__(self, name, fit_audit_text(redact_sql_credentials(value)))
        for name in ("duration_ms", "rows_affected"):
            value = getattr(self, name)
            if value is not None and (type(value) is not int or not 0 <= value < 2**63):
                raise ValueError("Invalid audit count")
        if self.engine_query_ids is not None:
            if not isinstance(self.engine_query_ids, tuple) or len(self.engine_query_ids) > 256:
                raise ValueError("Invalid engine query identities")
            for identity in self.engine_query_ids:
                _text(identity, 128)


_EVENT_COLUMNS = tuple(item.name for item in fields(AuditEvent))


class AuditRepository:
    def __init__(self, connection: psycopg.AsyncConnection[dict[str, Any]]) -> None:
        self._connection = connection
        self._require_transaction()

    def _require_transaction(self) -> None:
        if self._connection.info.transaction_status != TransactionStatus.INTRANS:
            raise ValueError("Audit storage requires an active metadata transaction")

    async def get(self, identity: AuditIdentity) -> dict[str, Any] | None:
        self._require_transaction()
        if not isinstance(identity, AuditIdentity):
            raise ValueError("Invalid audit identity")
        cursor = await self._connection.execute(
            "SELECT * FROM nova_meta.audit_log WHERE event_time=%s AND record_id=%s",
            (identity.event_time, identity.record_id),
        )
        return await cursor.fetchone()

    async def append(self, identity: AuditIdentity, event: AuditEvent) -> dict[str, Any]:
        """Replay only the same event, actor, version and composite identity."""
        self._require_transaction()
        if not isinstance(identity, AuditIdentity) or not isinstance(event, AuditEvent):
            raise ValueError("Invalid audit event")
        values = {name: getattr(event, name) for name in _EVENT_COLUMNS}
        if event.engine_query_ids is not None:
            values["engine_query_ids"] = list(event.engine_query_ids)
        parameters = [
            Jsonb(value) if name == "engine_query_ids" and value is not None else value
            for name, value in values.items()
        ]
        async with self._connection.transaction():
            cursor = await self._connection.execute(
                "INSERT INTO nova_meta.audit_log (event_time,record_id,"
                + ",".join(_EVENT_COLUMNS)
                + ") VALUES ("
                + ",".join(["%s"] * (2 + len(_EVENT_COLUMNS)))
                + ") ON CONFLICT (event_time,record_id) DO NOTHING RETURNING *",
                (identity.event_time, identity.record_id, *parameters),
            )
            created = await cursor.fetchone()
            if created is not None:
                return created
            existing = await self.get(identity)
            cursor = await self._connection.execute(
                "SELECT current_setting('nova.principal') AS user_name, "
                "current_setting('nova.active_role') AS active_role, "
                "current_setting('nova.security_context_version')::bigint "
                "AS security_context_version, "
                "current_setting('nova.principal_type') AS principal_type, "
                "session_user AS writer_role"
            )
            actor = await cursor.fetchone()
            if (
                existing is None
                or actor is None
                or existing["metadata_table"] is not None
                or any(existing[key] != value for key, value in {**values, **actor}.items())
            ):
                raise MetadataConflict()
            return existing
