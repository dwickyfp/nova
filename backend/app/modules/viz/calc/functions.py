@dataclass(frozen=True)
class FunctionSpec:
    name: str
    kind: FunctionKind
    category: str
    syntax: str
    description: str
    params: tuple[ParamKind, ...]
    min_args: int
    max_args: int | None
    returns: ReturnRule
    #: Allowed values for ``part`` parameters.
    parts: tuple[str, ...] = ()

    def param(self, index: int) -> ParamKind:
        if not self.params:
            return "any"
        return self.params[min(index, len(self.params) - 1)]

    def to_dict(self) -> dict[str, object]:
        return {
            "name": self.name,
            "kind": self.kind,
            "category": self.category,
            "syntax": self.syntax,
            "description": self.description,
        }


def _f(
    name: str,
    kind: FunctionKind,
    category: str,
    syntax: str,
    description: str,
    params: tuple[ParamKind, ...],
    returns: ReturnRule,
    *,
    min_args: int | None = None,
    max_args: int | None | Literal["same"] = "same",
    parts: tuple[str, ...] = (),
) -> FunctionSpec:
    minimum = len(params) if min_args is None else min_args
    maximum = len(params) if max_args == "same" else max_args
    return FunctionSpec(
        name, kind, category, syntax, description, params, minimum, maximum, returns, parts
    )


