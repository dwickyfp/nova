"""The calculation function catalog.

Each entry declares how a function type-checks (arity, parameter kinds,
return type), which evaluation level it belongs to (row, aggregate or table
calculation), and the documentation the Studio formula editor shows. SQL
lowering lives in :mod:`app.modules.viz.calc.lower`; every function there
maps onto StarRocks built-ins verified against the pinned engine.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

FunctionKind = Literal["row", "aggregate", "table"]

#: Parameter kinds. ``date`` accepts dates, datetimes and date-shaped text
#: (StarRocks casts text implicitly in date functions); ``part``/``int``/
#: ``direction`` must be constants.
ParamKind = Literal["number", "string", "date", "boolean", "any", "part", "int", "direction"]

#: Return rules: a data type, ``arg:N`` (the type of argument N) or
#: ``unify`` (the common type of all arguments).
ReturnRule = str

