CREATE TABLE nova_meta.audit_log (
    event_time timestamptz NOT NULL DEFAULT clock_timestamp(),
    record_id uuid NOT NULL DEFAULT gen_random_uuid(),
    log_id bigint GENERATED BY DEFAULT AS IDENTITY,
    query_id varchar(36),
    event_type varchar(64) NOT NULL,
    user_name varchar(128) DEFAULT current_setting('nova.principal',true),
    ip_address varchar(45),
    object_type varchar(64),
    object_name varchar(512),
    action varchar(128),
    sql_text text CHECK (char_length(sql_text)<=65533),
    status varchar(32),
    error_message text CHECK (char_length(error_message)<=65533),
    duration_ms bigint,
    rows_affected bigint,
    client_ip varchar(45),
    session_id varchar(64),
    rewritten_sql text CHECK (char_length(rewritten_sql)<=65533),
    file_id varchar(64),
    database_name varchar(128),
    schema_name varchar(128),
    active_role varchar(128) DEFAULT current_setting('nova.active_role',true),
    security_context_version bigint DEFAULT current_setting('nova.security_context_version',true)::bigint,
    decision varchar(32),
    ranger_policy_ids varchar(2048),
    nova_execution_id varchar(64),
    engine_query_ids jsonb,
    execution_purpose varchar(16),
    principal_type text DEFAULT current_setting('nova.principal_type',true),
    writer_role text DEFAULT session_user,
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    metadata_table text,
    metadata_key jsonb,
    metadata_revision bigint,
    PRIMARY KEY (event_time,record_id),
    CHECK ((metadata_table IS NULL AND metadata_key IS NULL AND metadata_revision IS NULL)
        OR (metadata_table IS NOT NULL AND metadata_key IS NOT NULL AND metadata_revision IS NOT NULL
            AND jsonb_typeof(metadata_key)='object' AND metadata_revision>0))
) PARTITION BY RANGE (event_time);
CREATE INDEX audit_log_actor_history ON nova_meta.audit_log (user_name,active_role,event_time DESC);
CREATE INDEX audit_log_query_history ON nova_meta.audit_log (query_id,event_time DESC);
CREATE INDEX audit_log_type_history ON nova_meta.audit_log (event_type,event_time DESC);

DO $partitions$
DECLARE start_at timestamptz; partition_name text;
BEGIN
    FOR month_offset IN 0..2 LOOP
        start_at := (date_trunc('month',clock_timestamp() AT TIME ZONE 'UTC')
            + make_interval(months=>month_offset)) AT TIME ZONE 'UTC';
        partition_name := 'audit_log_'||to_char(start_at AT TIME ZONE 'UTC','YYYYMM');
        EXECUTE format('CREATE TABLE nova_meta.%I PARTITION OF nova_meta.audit_log '
            'FOR VALUES FROM (%L) TO (%L)',partition_name,start_at,start_at+interval '1 month');
        EXECUTE format('ALTER TABLE nova_meta.%I ENABLE ROW LEVEL SECURITY',partition_name);
        EXECUTE format('ALTER TABLE nova_meta.%I FORCE ROW LEVEL SECURITY',partition_name);
    END LOOP;
END
$partitions$;
CREATE TABLE nova_meta.audit_log_unpartitioned PARTITION OF nova_meta.audit_log DEFAULT;
ALTER TABLE nova_meta.audit_log_unpartitioned ENABLE ROW LEVEL SECURITY;
ALTER TABLE nova_meta.audit_log_unpartitioned FORCE ROW LEVEL SECURITY;
ALTER TABLE nova_meta.audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE nova_meta.audit_log FORCE ROW LEVEL SECURITY;

CREATE POLICY audit_actor ON nova_meta.audit_log AS RESTRICTIVE
    TO nova_meta_app,nova_meta_readonly,nova_meta_owner USING (nova_meta.actor_context_valid());
CREATE POLICY audit_own_read ON nova_meta.audit_log FOR SELECT TO nova_meta_app,nova_meta_readonly
    USING (user_name=current_setting('nova.principal',true)
        AND active_role=current_setting('nova.active_role',true));
CREATE POLICY audit_admin_read ON nova_meta.audit_log FOR SELECT TO nova_meta_web,nova_meta_readonly
    USING (nova_meta.actor_is_administrator());
CREATE POLICY audit_insert ON nova_meta.audit_log FOR INSERT TO nova_meta_app
    WITH CHECK (user_name=current_setting('nova.principal',true)
        AND active_role=current_setting('nova.active_role',true)
        AND security_context_version=current_setting('nova.security_context_version',true)::bigint
        AND principal_type=current_setting('nova.principal_type',true)
        AND writer_role=session_user AND metadata_table IS NULL);
CREATE POLICY audit_trigger_insert ON nova_meta.audit_log FOR INSERT TO nova_meta_owner
    WITH CHECK (pg_has_role(session_user,'nova_meta_app','MEMBER')
        AND user_name=current_setting('nova.principal',true)
        AND active_role=current_setting('nova.active_role',true)
        AND security_context_version=current_setting('nova.security_context_version',true)::bigint
        AND principal_type=current_setting('nova.principal_type',true)
        AND writer_role=session_user AND metadata_table IS NOT NULL);
GRANT SELECT ON nova_meta.audit_log TO nova_meta_app,nova_meta_readonly;
GRANT INSERT (event_time,record_id,query_id,event_type,ip_address,object_type,object_name,action,
    sql_text,status,error_message,duration_ms,rows_affected,client_ip,session_id,rewritten_sql,
    file_id,database_name,schema_name,decision,ranger_policy_ids,nova_execution_id,engine_query_ids,
    execution_purpose) ON nova_meta.audit_log TO nova_meta_app;
GRANT USAGE ON SEQUENCE nova_meta.audit_log_log_id_seq TO nova_meta_app;

CREATE FUNCTION nova_meta.audit_runtime_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $body$
BEGIN
    IF pg_has_role(session_user,'nova_meta_app','MEMBER') AND NOT EXISTS
        (SELECT 1 FROM pg_roles WHERE rolname=session_user AND rolsuper) THEN
        IF NOT nova_meta.actor_context_valid()
           OR (NEW.event_type='metadata' AND current_user<>'nova_meta_owner') THEN
            RAISE EXCEPTION 'Audit operation is not authorized' USING ERRCODE='42501';
        END IF;
        IF NOT isfinite(NEW.event_time) OR NEW.record_id='00000000-0000-0000-0000-000000000000'::uuid THEN
            RAISE EXCEPTION 'Invalid audit identity' USING ERRCODE='23514';
        END IF;
        NEW.recorded_at:=clock_timestamp();
    END IF;
    RETURN NEW;
END
$body$;
CREATE TRIGGER audit_runtime_guard BEFORE INSERT ON nova_meta.audit_log
    FOR EACH ROW EXECUTE FUNCTION nova_meta.audit_runtime_guard();

CREATE FUNCTION nova_meta.audit_metadata_change() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog SET row_security=on AS $body$
DECLARE object_key jsonb; object_identity text; revision bigint; deleted boolean;
BEGIN
    IF NOT pg_has_role(session_user,'nova_meta_app','MEMBER') OR EXISTS
        (SELECT 1 FROM pg_roles WHERE rolname=session_user AND rolsuper) THEN RETURN NULL; END IF;
    IF TG_TABLE_SCHEMA<>'nova_meta' OR TG_TABLE_NAME NOT IN
        ('config_user_preferences','config_ai_providers','config_ai_models','config_model_aliases')
       OR TG_OP NOT IN ('INSERT','UPDATE') OR NOT nova_meta.actor_context_valid() THEN
        RAISE EXCEPTION 'Invalid metadata audit source' USING ERRCODE='42501';
    END IF;
    IF TG_TABLE_NAME='config_user_preferences' THEN
        object_key:=jsonb_build_object('user_name',NEW.user_name,'pref_key',NEW.pref_key);
        object_identity:=NEW.user_name||'/'||NEW.pref_key;
        revision:=NEW.revision;
    ELSE
        object_key:=jsonb_build_object('id',NEW.id);
        object_identity:=NEW.id;
        revision:=NEW.metadata_revision;
    END IF;
    deleted:=NEW.is_deleted;
    INSERT INTO nova_meta.audit_log (query_id,event_type,object_type,object_name,action,status,
        decision,metadata_table,metadata_key,metadata_revision)
    VALUES (gen_random_uuid()::text,'metadata',TG_TABLE_NAME,object_identity,
        CASE WHEN deleted THEN 'DELETE' WHEN TG_OP='INSERT' THEN 'CREATE' ELSE 'UPDATE' END,
        'SUCCESS','ALLOW',TG_TABLE_NAME,object_key,revision);
    RETURN NULL;
END
$body$;
CREATE TRIGGER preference_audit AFTER INSERT OR UPDATE ON nova_meta.config_user_preferences
    FOR EACH ROW EXECUTE FUNCTION nova_meta.audit_metadata_change();
CREATE TRIGGER provider_audit AFTER INSERT OR UPDATE ON nova_meta.config_ai_providers
    FOR EACH ROW EXECUTE FUNCTION nova_meta.audit_metadata_change();
CREATE TRIGGER model_audit AFTER INSERT OR UPDATE ON nova_meta.config_ai_models
    FOR EACH ROW EXECUTE FUNCTION nova_meta.audit_metadata_change();
CREATE TRIGGER alias_audit AFTER INSERT OR UPDATE ON nova_meta.config_model_aliases
    FOR EACH ROW EXECUTE FUNCTION nova_meta.audit_metadata_change();

CREATE OR REPLACE FUNCTION nova_meta.ai_configuration_complete() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $body$
DECLARE types text[]; selected_type text; snapshot jsonb; recorded jsonb;
BEGIN
    -- Runtime writes require an intent. Cutover must separately validate
    -- privileged imports before publishing the metadata epoch.
    IF NOT pg_has_role(session_user,'nova_meta_app','MEMBER') OR EXISTS
        (SELECT 1 FROM pg_roles WHERE rolname=session_user AND rolsuper) THEN RETURN NULL; END IF;
    IF TG_TABLE_NAME='config_model_aliases' THEN
        types:=ARRAY[NEW.function_type];
        IF TG_OP='UPDATE' THEN types:=array_append(types,OLD.function_type); END IF;
    ELSIF TG_TABLE_NAME='config_ai_providers' THEN
        SELECT array_agg(DISTINCT function_type) INTO types FROM nova_meta.config_model_aliases
            WHERE provider_id=NEW.id AND NOT is_deleted;
    ELSE
        SELECT array_agg(DISTINCT function_type) INTO types FROM nova_meta.config_model_aliases
            WHERE model_id=NEW.id AND NOT is_deleted;
    END IF;
    FOREACH selected_type IN ARRAY coalesce(types,ARRAY[]::text[]) LOOP
        snapshot:=nova_meta.ai_function_snapshot(selected_type);
        SELECT d.payload::jsonb INTO recorded FROM nova_meta.ai_function_heads h
            JOIN nova_meta.ai_function_definitions d ON d.id=h.definition_id
            WHERE h.function_type=selected_type;
        IF recorded IS NULL AND snapshot->>'mode'='unconfigured' THEN CONTINUE; END IF;
        IF snapshot IS DISTINCT FROM recorded THEN
            RAISE EXCEPTION 'AI configuration requires its registration intent' USING ERRCODE='23514';
        END IF;
    END LOOP;
    RETURN NULL;
END
$body$;
