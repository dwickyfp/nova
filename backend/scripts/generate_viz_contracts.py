def typescript(node: dict[str, Any]) -> str:
    if "$ref" in node:
        return str(node["$ref"]).rsplit("/", 1)[1]
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(value) for value in node["enum"])
    for union in ("anyOf", "oneOf"):
        if union in node:
            return " | ".join(typescript(child) for child in node[union])
    kind = node.get("type")
    if kind in {"string", "boolean", "null"}:
        return str(kind)
    if kind in {"integer", "number"}:
        return "number"
    if kind == "array":
        return "Array<" + typescript(node["items"]) + ">"
    if kind == "object":
        required = set(node.get("required", ()))
        fields = [
            f"  {json.dumps(name)}{'' if name in required else '?'}: {typescript(child)};"
            for name, child in node.get("properties", {}).items()
        ]
        return "{\n" + "\n".join(fields) + "\n}"
    raise ValueError(f"Unsupported JSON Schema construct: {sorted(node)}")


def outputs() -> dict[str, str]:
    schema = NativeContracts.model_json_schema()
    serialized = json.dumps(schema, indent=2, sort_keys=True)
    declarations = ["// Generated by backend/scripts/generate_viz_contracts.py.\n"]
    for name, definition in sorted(schema["$defs"].items()):
        declarations.append(f"export type {name} = {typescript(definition)};\n")
    schema_module = declarations[0] + "const schema = " + serialized + ";\nexport default schema;\n"
    return {
        "schema.json": serialized + "\n",
        "schema.ts": schema_module,
        "types.ts": "\n".join(declarations),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = outputs()
    if args.check:
        drift = [
            name
            for name, text in generated.items()
            if not (TARGET / name).exists() or (TARGET / name).read_text() != text
        ]
        if drift:
            print("Native Viz contract drift: " + ", ".join(drift))
            return 1
        print("Native Viz contracts match the backend schema")
        return 0
    TARGET.mkdir(parents=True, exist_ok=True)
    for name, text in generated.items():
        (TARGET / name).write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
